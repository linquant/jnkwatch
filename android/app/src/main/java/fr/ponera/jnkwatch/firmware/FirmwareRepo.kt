package fr.ponera.jnkwatch.firmware

import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL
import java.security.MessageDigest

/**
 * Firmware update source for BLE OTA. The phone fetches a small JSON manifest and,
 * if it advertises a newer version than the connected watch, downloads the raw
 * .bin (verifying its SHA-256 and size) so WatchBleClient.performOta can stream it.
 * Mirrors the HttpURLConnection pattern used by weather/WeatherRepo.kt.
 *
 * Manifest JSON shape:
 *   { "major": 1, "minor": 1, "size": 1392448,
 *     "sha256": "<64 hex>", "url": "https://.../jnkwatch.bin" }
 */
object FirmwareRepo {
    private const val TAG = "FirmwareRepo"

    /** Update manifest: the raw `firmware.json` on the repo's default branch.
     *  Generated by tools/make-firmware-manifest.sh and committed; the `url` it
     *  contains points at the .bin (a GitLab release asset by default).
     *  The project must be public for this unauthenticated GET to succeed. */
    const val MANIFEST_URL =
        "https://gitlab.com/johann.nowacki/jnkwatch/-/raw/main/firmware.json"

    data class Manifest(
        val major: Int,
        val minor: Int,
        val size: Int,
        val sha256: ByteArray,
        val url: String,
    ) {
        fun isNewerThan(devMajor: Int, devMinor: Int): Boolean =
            major > devMajor || (major == devMajor && minor > devMinor)
    }

    suspend fun fetchManifest(url: String = MANIFEST_URL): Manifest? = withContext(Dispatchers.IO) {
        val body = httpGetText(url) ?: return@withContext null
        try {
            val j = JSONObject(body)
            val sha = hexToBytes(j.getString("sha256"))
            if (sha.size != 32) { Log.w(TAG, "manifest sha256 not 32 bytes"); return@withContext null }
            Manifest(
                major = j.getInt("major"),
                minor = j.getInt("minor"),
                size = j.getInt("size"),
                sha256 = sha,
                url = j.getString("url"),
            )
        } catch (e: Exception) {
            Log.w(TAG, "manifest parse failed: ${e.message}")
            null
        }
    }

    /** Download the image, verifying size and SHA-256. Returns null on any mismatch. */
    suspend fun download(m: Manifest): ByteArray? = withContext(Dispatchers.IO) {
        val bytes = httpGetBytes(m.url) ?: return@withContext null
        if (bytes.size != m.size) {
            Log.w(TAG, "size mismatch: got ${bytes.size}, expected ${m.size}")
            return@withContext null
        }
        val digest = MessageDigest.getInstance("SHA-256").digest(bytes)
        if (!digest.contentEquals(m.sha256)) {
            Log.w(TAG, "sha256 mismatch on downloaded image")
            return@withContext null
        }
        bytes
    }

    private fun httpGetText(url: String): String? = openGet(url)?.use { c ->
        if (c.responseCode != 200) { Log.w(TAG, "GET $url -> ${c.responseCode}"); return null }
        c.inputStream.bufferedReader().use { it.readText() }
    }

    private fun httpGetBytes(url: String): ByteArray? = openGet(url)?.use { c ->
        if (c.responseCode != 200) { Log.w(TAG, "GET $url -> ${c.responseCode}"); return null }
        c.inputStream.use { it.readBytes() }
    }

    private inline fun <T> HttpURLConnection.use(block: (HttpURLConnection) -> T): T =
        try { block(this) } finally { disconnect() }

    private fun openGet(url: String): HttpURLConnection? = try {
        (URL(url).openConnection() as HttpURLConnection).apply {
            requestMethod = "GET"
            connectTimeout = 8000
            readTimeout = 20000
        }
    } catch (e: Exception) {
        Log.w(TAG, "open $url failed: ${e.message}")
        null
    }

    private fun hexToBytes(hex: String): ByteArray {
        val s = hex.trim()
        if (s.length % 2 != 0) return ByteArray(0)
        return ByteArray(s.length / 2) {
            ((Character.digit(s[it * 2], 16) shl 4) + Character.digit(s[it * 2 + 1], 16)).toByte()
        }
    }
}
